const fs = require('node:fs');
const assert = require('node:assert/strict');
const { randomBytes, createHash } = require('node:crypto');
const { Connection, PublicKey, Keypair, Transaction, sendAndConfirmTransaction } = require('@solana/web3.js');
const { getAssociatedTokenAddressSync, createAssociatedTokenAccountIdempotentInstruction } = require('@solana/spl-token');
const c = require('./booking-client.cjs');
const MINT = new PublicKey('4zMMC9srt5Ri5X14GAgXhaHii3GnPAEERYPJgZJDncDU');
const discriminator = name => createHash('sha256').update(`account:${name}`).digest().subarray(0, 8);
(async () => {
  const connection = new Connection(process.env.VYNX_DEVNET_RPC_URL || 'https://api.devnet.solana.com', 'finalized');
  assert.equal(await connection.getGenesisHash(), 'EtWTRABZaYq6iMfeYKouRu166VU2xqa1wcaWoxPkrZBG');
  const load = path => Keypair.fromSecretKey(Uint8Array.from(JSON.parse(fs.readFileSync(path))));
  const payer = load('.wallets/devnet-deployer.json'), quote = load('.wallets/booking-devnet-quote.json');
  const authorities = JSON.parse(fs.readFileSync('booking-devnet-authorities.json'));
  const creator = load('.wallets/devnet-creator.json');
  const config = await connection.getAccountInfo(c.config(), 'finalized');
  assert(config?.owner.equals(c.PROGRAM_ID)); assert.equal(config.data.length, 105);
  assert(config.data.subarray(0, 8).equals(discriminator('Config')));
  assert.equal(new PublicKey(config.data.subarray(8, 40)).toBase58(), authorities.quote);
  assert.equal(new PublicKey(config.data.subarray(40, 72)).toBase58(), authorities.resolver);
  assert.equal(new PublicKey(config.data.subarray(72, 104)).toBase58(), MINT.toBase58());
  const pd = await connection.getAccountInfo(c.programDataPda(), 'finalized');
  const binary = fs.readFileSync('target/deploy/vynx_booking.so');
  assert(pd?.owner.equals(c.LOADER)); assert(pd.data.subarray(45, 45 + binary.length).equals(binary));
  const source = getAssociatedTokenAddressSync(MINT, payer.publicKey);
  const ataSignature = await sendAndConfirmTransaction(connection, new Transaction().add(createAssociatedTokenAccountIdempotentInstruction(payer.publicKey, source, payer.publicKey, MINT)), [payer], { commitment: 'finalized' });
  const balance = (await connection.getTokenAccountBalance(source, 'finalized')).value.amount;
  assert.equal(balance, '0', 'This negative smoke test requires an empty test-USDC source.');
  const clock = await connection.getAccountInfo(new PublicKey('SysvarC1ock11111111111111111111111111111111'), 'finalized');
  const now = Number(clock.data.readBigInt64LE(32));
  const id = randomBytes(16);
  const terms = { payer: payer.publicKey, quote: quote.publicKey, creator: creator.publicKey, mint: MINT, source, id, amount: 10000n, start: now + 2 * 86400, end: now + 2 * 86400 + 1800, expires: now + 600 };
  async function simulate(ix, signers) {
    const latest = await connection.getLatestBlockhash('finalized');
    const transaction = new Transaction({ feePayer: payer.publicKey, ...latest }).add(ix);
    transaction.sign(...signers);
    return (await connection.simulateTransaction(transaction)).value;
  }
  const stranger = Keypair.generate();
  const unauthorized = await simulate(c.fund({ ...terms, quote: stranger.publicKey }), [payer, stranger]);
  assert(unauthorized.err); assert(unauthorized.logs.some(line => /quote_authority|ConstraintHasOne/.test(line)));
  const insufficient = await simulate(c.fund(terms), [payer, quote]);
  assert(insufficient.err); assert(insufficient.logs.some(line => /insufficient funds/i.test(line)));
  assert.equal((await connection.getTokenAccountBalance(source, 'finalized')).value.amount, balance);
  assert.equal(await connection.getAccountInfo(c.booking(id), 'finalized'), null);
  assert.equal(await connection.getAccountInfo(c.vault(id), 'finalized'), null);
  const record = { network: 'devnet', programId: c.PROGRAM_ID.toBase58(), configVerified: true, binaryVerified: true, quote: authorities.quote, resolver: authorities.resolver, mint: MINT.toBase58(), source: source.toBase58(), sourceBalanceUnits: balance, ataSignature, unauthorizedQuoteRejected: true, insufficientUsdcRejected: true, failedFundingCreatesNoReceiptOrVault: true, successfulFunding: 'Not run: development wallet has no test USDC', verifiedAt: new Date().toISOString() };
  fs.writeFileSync('booking-devnet-smoke.json', JSON.stringify(record, null, 2) + '\n');
  console.log(JSON.stringify(record));
})().catch(error => { console.error(error.message); process.exitCode = 1; });

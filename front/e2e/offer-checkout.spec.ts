import { test, expect } from './test';
import { createClient } from '@supabase/supabase-js';
import { Keypair } from '@solana/web3.js';
import AxeBuilder from '@axe-core/playwright';
import { installWallet, signIn } from './wallet';
import { EMPTY_DRAFT } from '../lib/creator-draft';

test('offer details remain separate from Vynx checkout and one-time payment receipts recover after reload', async ({ browser }) => {
  const db = createClient(process.env.SUPABASE_URL!,process.env.SUPABASE_SECRET_KEY!);
  const context = await browser.newContext({viewport:{width:390,height:844}}), fan = await installWallet(context);
  const alias = `offer_${Date.now()}`, creator = Keypair.generate().publicKey.toBase58();
  const offer = {id:'guide',type:'digital',title:'Portfolio guide',description:'A guide for your next project.',price:'25.5',url:'https://example.com/guide',billingPeriod:'session'};
  const design = {...EMPTY_DRAFT,alias,name:'Guide creator',offers:[offer]};
  expect((await db.from('cards_users').insert({username:alias,wallet_address:creator,display_name:design.name,design,published:true})).error).toBeNull();
  expect((await db.from('cards_users').insert({username:`buyer_${Date.now()}`,wallet_address:fan.publicKey.toBase58()})).error).toBeNull();
  const page = await context.newPage();
  await signIn(page,'/dashboard/card');
  await page.getByRole('tab',{name:'Offers',exact:true}).click();
  await page.getByRole('button',{name:'Digital products',exact:true}).click();
  await page.getByLabel('Offer title 1',{exact:true}).fill('Without a details page');
  await page.getByLabel('Price 1 (USDC)',{exact:true}).fill('12');
  await expect(page.getByLabel('More details page URL 1 (optional)',{exact:true})).toHaveValue('');
  await page.getByRole('button',{name:'Save and publish',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'Design published'})).toBeVisible();
  await page.goto(`/${alias}`);
  await page.getByRole('button',{name:/^Portfolio guide/}).click();
  const dialog = page.getByRole('dialog',{name:'Offer: Portfolio guide',exact:true});
  await expect(dialog.getByLabel('Payment signature to recover this purchase')).toHaveCount(0);
  await expect(dialog.getByRole('button',{name:'Verify existing payment',exact:true})).toHaveCount(0);
  await expect(dialog.getByRole('button',{name:'Recover expired payment',exact:true})).toHaveCount(0);
  await expect(dialog.getByRole('link',{name:'More details',exact:true})).toHaveAttribute('href','https://example.com/guide');
  await expect(dialog.getByRole('button',{name:'Connect wallet to pay',exact:true})).toBeVisible();
  expect((await new AxeBuilder({page}).include('[role=dialog]').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([]);
  const origin = process.env.E2E_BASE_URL!;
  const bad = {action:'checkout',id:crypto.randomUUID(),alias,offer:offer.id,expected_price_units:1,accepted_policy:'vynx-offer-devnet-v1'};
  expect((await page.request.post('/api/offer-purchases',{headers:{origin},data:bad})).status()).toBe(409);
  expect((await page.request.post('/api/offer-purchases',{headers:{origin:'https://evil.example'},data:bad})).status()).toBe(403);
  await dialog.getByRole('checkbox').check();
  await page.evaluate(()=>{(window as unknown as {walletTestTransactionError:{code:number;message:string}}).walletTestTransactionError={code:4001,message:'User rejected the transaction'};});
  await dialog.getByRole('button',{name:'Connect wallet to pay',exact:true}).click();
  await page.getByRole('dialog',{name:'Sign in',exact:true}).getByRole('button',{name:'Phantom',exact:true}).click();
  const pay = dialog.getByRole('button',{name:'Approve and pay 25.5 USDC',exact:true});
  await pay.click();
  await expect(dialog.getByRole('status').filter({hasText:'Wallet approval was cancelled'})).toBeVisible();
  const pending = await db.from('offer_purchases').select('*').eq('creator_alias',alias).single();
  expect(pending.error).toBeNull(); expect(pending.data!.price_units).toBe(25500000);
  const retryCheckout = {...bad,id:pending.data!.id,expected_price_units:25500000};
  const concurrent = await Promise.all([page.request.post('/api/offer-purchases',{headers:{origin},data:retryCheckout}),page.request.post('/api/offer-purchases',{headers:{origin},data:retryCheckout})]);
  for (const response of concurrent) { expect(response.status()).toBe(200); expect((await response.json()).transaction).toBe(pending.data!.transaction); }
  expect((await page.request.post('/api/offer-purchases',{headers:{origin},data:{...retryCheckout,offer:'different'}})).status()).toBe(409);
  const recoveryKey = `vynx:offer:v1:${fan.publicKey.toBase58()}:${alias}:${offer.id}`;
  await page.evaluate(({key,id})=>localStorage.setItem(key,JSON.stringify({id,sending:true})),{key:recoveryKey,id:pending.data!.id});
  await pay.click();
  await expect(dialog.getByRole('status').filter({hasText:'A transfer may already have been submitted'})).toBeVisible();
  expect((await db.from('offer_purchases').select('state').eq('id',pending.data!.id).single()).data!.state).toBe('awaiting_payment');
  // This fixture deliberately did not submit a transfer; restore the known rejection.
  await page.evaluate(({key,id})=>localStorage.setItem(key,JSON.stringify({id})),{key:recoveryKey,id:pending.data!.id});
  await pay.click();
  await expect(dialog.getByRole('status').filter({hasText:'Receipt:'})).toContainText('Payment confirmed');
  const paid = await db.from('offer_purchases').select('*').eq('id',pending.data!.id).single();
  expect(paid.data!.state).toBe('paid'); expect(paid.data!.payment_signature).toBeTruthy();
  const confirm = {action:'confirm',id:paid.data!.id,signature:paid.data!.payment_signature};
  expect((await page.request.post('/api/offer-purchases',{headers:{origin},data:confirm})).status()).toBe(200);
  await page.reload();
  await page.getByRole('button',{name:/^Portfolio guide/}).click();
  await expect(dialog.getByRole('status').filter({hasText:'Receipt:'})).toContainText('Payment confirmed');
  await expect(dialog.getByRole('button',{name:/Approve and pay/})).toHaveCount(0);
  expect((await db.from('offer_purchases').select('id').eq('creator_alias',alias)).data).toHaveLength(1);
  const otherContext = await browser.newContext();
  const other = await installWallet(otherContext);
  expect((await db.from('cards_users').insert({username:`other_${Date.now()}`,wallet_address:other.publicKey.toBase58()})).error).toBeNull();
  const otherPage = await otherContext.newPage(); await signIn(otherPage,'/dashboard/card');
  await expect.poll(async()=> (await (await otherPage.request.get('/api/auth/session')).json()).wallet).toBe(other.publicKey.toBase58());
  expect((await otherPage.request.post('/api/offer-purchases',{headers:{origin},data:confirm})).status()).toBe(404);
  await context.close(); await otherContext.close();
});

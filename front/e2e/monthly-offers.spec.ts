import { test, expect } from './test';
import AxeBuilder from '@axe-core/playwright';
import { createClient } from '@supabase/supabase-js';
import { installWallet, signIn } from './wallet';

const db = () => createClient(process.env.SUPABASE_URL!, process.env.SUPABASE_SECRET_KEY!);
test('monthly offers publish, reserve every weekly session, require wallet approval, and track renewals', async ({ browser }, testInfo) => {
  const creatorContext = await browser.newContext();
  const fanContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const creator = await installWallet(creatorContext), fan = await installWallet(fanContext);
  const alias = `monthly_${Date.now()}`;
  expect((await db().from('cards_users').insert([{ wallet_address: creator.publicKey.toBase58(), username: alias }, { wallet_address: fan.publicKey.toBase58(), username: `mf_${Date.now()}` }])).error).toBeNull();
  const ownerPage = await creatorContext.newPage();
  await signIn(ownerPage, '/dashboard/card');
  await ownerPage.getByLabel('Creator name', { exact: true }).fill('Monthly coach');
  await ownerPage.getByRole('tab', { name: 'Offers', exact: true }).click();
  await ownerPage.getByRole('button', { name: 'Bookings and video calls', exact: true }).click();
  await ownerPage.getByLabel('Offer title 1', { exact: true }).fill('Monthly mentoring');
  await ownerPage.getByLabel('Description 1', { exact: true }).fill('Two weekly sessions to improve your portfolio.');
  await ownerPage.getByLabel('Price 1 (USDC)', { exact: true }).fill('40');
  await ownerPage.getByRole('combobox', { name: 'Billing period 1', exact: true }).selectOption('month');
  await ownerPage.getByRole('combobox', { name: 'Session duration 1', exact: true }).selectOption('90');
  const calendar = ownerPage.getByLabel('Weekly session calendar for offer 1', { exact: true });
  await calendar.getByRole('button', { name: /^Monday,/ }).first().click();
  await expect(calendar.getByRole('button', { name: /^Monday,.*repeats weekly/ })).toHaveCount(await calendar.getByRole('button', { name: /^Monday,/ }).count());
  await calendar.getByRole('button', { name: /^Thursday,/ }).first().click();
  // Keyboard activation toggles every occurrence once and preserves the other day.
  const thursday = calendar.getByRole('button', { name: /^Thursday,/ }).first();
  await thursday.focus(); await thursday.press('Space');
  await expect(calendar.getByRole('button', { name: /^Thursday,.*repeats weekly/ })).toHaveCount(0);
  await thursday.press('Enter');
  await expect(calendar.getByRole('button', { name: /^Thursday,.*repeats weekly/ })).toHaveCount(await calendar.getByRole('button', { name: /^Thursday,/ }).count());
  await ownerPage.getByLabel('Starting time for offer 1, session 2', { exact: true }).fill('15:00');
  const firstStart = ownerPage.getByLabel('Starting time for offer 1, session 1', { exact: true });
  const secondStart = ownerPage.getByLabel('Starting time for offer 1, session 2', { exact: true });
  await firstStart.focus(); await firstStart.press('Tab');
  await expect(secondStart).toBeFocused();
  await secondStart.press('Shift+Tab'); await expect(firstStart).toBeFocused();
  await ownerPage.getByLabel('Ending hour for offer 1, session 1', { exact: true }).fill('12:00');
  await ownerPage.getByLabel('Ending hour for offer 1, session 2', { exact: true }).fill('15:30');
  await ownerPage.getByRole('button', { name: 'Save and publish', exact: true }).click();
  await expect(ownerPage.getByRole('alert').filter({ hasText: 'allow the full session duration' })).toBeVisible();
  await ownerPage.getByLabel('Ending hour for offer 1, session 2', { exact: true }).fill('18:00');
  await ownerPage.getByLabel('More details page URL 1 (optional)', { exact: true }).fill('https://example.com/mentoring');
  for (const width of [320, 390, 1280]) {
    await ownerPage.setViewportSize({ width, height: 900 });
    expect(await ownerPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  expect((await new AxeBuilder({ page: ownerPage }).include('[data-slot=calendar]').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
  await calendar.screenshot({ path: testInfo.outputPath('weekly-session-calendar.png') });
  await ownerPage.getByRole('button', { name: 'Save and publish', exact: true }).click();
  await expect(ownerPage.getByRole('status').filter({ hasText: 'Design published' })).toBeVisible();
  const saved = await db().from('cards_users').select('design').eq('username', alias).single();
  expect(saved.data!.design.offers[0].schedule).toHaveLength(2);
  expect(saved.data!.design.offers[0].durationMinutes).toBe(90);
  expect(saved.data!.design.offers[0].schedule.map((item: {endTime: string}) => item.endTime)).toEqual(['12:00', '18:00']);
  const page = await fanContext.newPage();
  await signIn(page, '/dashboard/monthly');
  await expect(page.getByRole('heading', { name: 'Monthly plans and payments', exact: true })).toBeVisible();
  await page.goto(`/${alias}`);
  await page.getByRole('button', { name: /^Monthly mentoring/ }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByText(/Available: Monday 09:00–12:00 · Thursday 15:00–18:00/)).toBeVisible();
  await expect(dialog.getByRole('link', { name: 'More details', exact: true })).toHaveAttribute('href', 'https://example.com/mentoring');
  await dialog.getByRole('checkbox').check();
  await dialog.getByRole('button', { name: 'Review and reserve my first month' }).click();
  await page.getByRole('dialog', { name: 'Sign in', exact: true }).getByRole('button', { name: 'Phantom', exact: true }).click();
  await expect(dialog.getByText('Payment requested: 40 USDC for this month', { exact: true })).toBeVisible();
  await dialog.getByText(/Review all \d+ scheduled sessions/).click();
  const invoices = await db().from('monthly_invoices').select('*');
  const invoice = invoices.data!.find(item => item.state === 'awaiting_payment');
  expect(invoice).toBeTruthy();
  const sessions = await db().from('call_bookings').select('*').eq('monthly_invoice_id', invoice.id);
  expect(sessions.data!.length).toBeGreaterThanOrEqual(8);
  expect(sessions.data!.every(item => item.state === 'awaiting_payment')).toBe(true);
  expect(sessions.data!.every(item => Date.parse(item.ends_at) - Date.parse(item.starts_at) === 90 * 60_000)).toBe(true);
  const pay = dialog.getByRole('button', { name: 'Approve and pay 40 USDC for this month' });
  await page.evaluate(() => { (window as unknown as { walletTestReject: boolean }).walletTestReject = true; });
  await pay.click();
  await expect(dialog.getByRole('status').filter({ hasText: 'Wallet approval was cancelled' })).toBeVisible();
  await pay.click();
  await expect(dialog.getByText(/Next payment due:/)).toBeVisible();
  await expect(dialog.getByText('Payment history and sessions (1 paid months)', { exact: true })).toBeVisible();
  const confirmed = await db().from('monthly_invoices').select('*').eq('id', invoice.id).single();
  expect(confirmed.data!.state).toBe('paid');
  expect(confirmed.data!.payment_signature).toBeTruthy();
  const active = await db().from('call_bookings').select('id,state,payment_signature').eq('monthly_invoice_id', invoice.id);
  expect(active.data!.every(item => item.state === 'confirmed' && !item.payment_signature)).toBe(true);
  const signature = confirmed.data!.payment_signature;
  const origin = process.env.E2E_BASE_URL!;
  expect((await page.request.post('/api/monthly-offers', { headers: { origin }, data: { action: 'confirm', invoice: invoice.id, signature } })).status()).toBe(200);
  expect((await page.request.post('/api/monthly-offers', { headers: { origin }, data: { action: 'reserve', subscription: invoice.subscription_id, accepted_policy: 'vynx-monthly-devnet-v1' } })).status()).toBe(409);
  const calls = await (await page.request.get('/api/calls')).json();
  expect(calls.calls.filter((call: { billing_period: string }) => call.billing_period === 'month')).toHaveLength(active.data!.length);
  const privateCall = await page.request.get(`/api/calls?id=${active.data![0].id}`);
  expect(privateCall.status()).toBe(200);
  expect((await privateCall.json()).call.billing_period).toBe('month');
  // Advance the paid month in the isolated DB, then exercise a second explicit approval.
  const earlier = (date: string) => new Date(Date.parse(date) - 60 * 86400_000).toISOString();
  for (const item of sessions.data!) expect((await db().from('call_bookings').update({ starts_at: earlier(item.starts_at), ends_at: earlier(item.ends_at) }).eq('id', item.id)).error).toBeNull();
  expect((await db().from('monthly_invoices').update({ period_start: earlier(invoice.period_start), period_end: earlier(invoice.period_end) }).eq('id', invoice.id)).error).toBeNull();
  expect((await db().from('monthly_subscriptions').update({ paid_until: new Date(Date.now() - 86400_000).toISOString() }).eq('id', invoice.subscription_id)).error).toBeNull();
  await page.goto('/dashboard/monthly');
  await expect(page.getByText(/Renewal payment requested:/)).toBeVisible();
  await page.getByRole('button', { name: 'Review and pay next month', exact: true }).click();
  await page.getByRole('dialog', { name: 'Sign in', exact: true }).getByRole('button', { name: 'Phantom', exact: true }).click();
  await expect(page.getByText('Payment requested: 40 USDC for this month', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Approve and pay 40 USDC for this month', exact: true }).click();
  await expect(page.getByText('Payment history and sessions (2 paid months)', { exact: true })).toBeVisible();
  const history = await db().from('monthly_invoices').select('payment_signature').eq('subscription_id', invoice.subscription_id).eq('state', 'paid');
  expect(new Set(history.data!.map(item => item.payment_signature)).size).toBe(2);
  await page.getByRole('button', { name: 'Stop renewals', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm stop renewals', exact: true }).click();
  await expect(page.getByText('Renewals stopped', { exact: true })).toBeVisible();
  expect((await db().from('call_bookings').select('state').eq('monthly_invoice_id', invoice.id)).data!.every(item => item.state === 'confirmed')).toBe(true);
  for (const width of [320, 390, 430]) {
    await page.setViewportSize({ width, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  await page.screenshot({ path: testInfo.outputPath('monthly-plans-mobile.png'), fullPage: true });
  await ownerPage.goto('/dashboard/monthly');
  await expect(ownerPage.getByText('40 USDC / month · Creator', { exact: true })).toBeVisible();
  await Promise.all([creatorContext.close(), fanContext.close()]);
});
